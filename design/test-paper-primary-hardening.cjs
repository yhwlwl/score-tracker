'use strict';
const assert=require('node:assert/strict'),crypto=require('node:crypto'),vm=require('node:vm');
const {harness,input,uid,rid}=require('./test-paper-review.cjs');
(async()=>{
  const pair=crypto.generateKeyPairSync('ed25519'),key=pair.publicKey.export({type:'spki',format:'der'}).toString('base64');
  const {makeBridge}=await import('../ops/paper-preview-bridge.mjs');let target,calls=0;
  const bridge=makeBridge(key,async (url,options)=>{calls++;target=url;assert.equal(options.redirect,'manual');return new Response('fixture',{headers:{'content-type':'image/jpeg'}});});
  const ref=crypto.randomUUID(),token=crypto.randomBytes(32).toString('base64url');
  const message=`scoretracker-paper-bridge-v1\n${rid}\n${ref}\n${token}`;
  const signature=crypto.sign(null,Buffer.from(message),pair.privateKey).toString('base64url');
  const req=body=>new Request('https://bridge.test/read',{method:'POST',body:JSON.stringify(body)});
  const body={request_id:rid,asset:ref,token,signature};
  assert.equal(await (await bridge(req(body))).text(),'fixture');assert.equal(target.origin,'https://assets.tantantan.tech');assert.equal(target.pathname,'/paper-preview-read');
  assert.equal((await bridge(req({...body,asset:crypto.randomUUID()}))).status,404);assert.equal(calls,1,'invalid signatures never proxy requests');

  const h=harness();await h.init();const db=vm.runInContext('db',h.scope);
  let r=await h.call({action:'save_materials',...input,options:{purpose:'record',config_version:2}});assert.equal(r.status,200);
  const img=Buffer.from('synthetic private image'),hash=crypto.createHash('sha256').update(img).digest('hex'),cap=crypto.randomBytes(32).toString('base64url');
  const assets=Array.from({length:11},(_,i)=>({path:`${uid}/${rid}/${i+1}-${crypto.randomUUID()}`,page:1,mime:'image/jpeg',bytes:img.length,ecs_ref:crypto.randomUUID(),ecs_read_token:cap,ecs_bridge_sig:signature,sha256:hash}));
  h.tables.score_tracker_paper_materials[0].options.ecs_mirror='preview-v2-primary';
  h.tables.score_tracker_paper_materials[0].pages=[{...assets[0],role:'paper',detail_images:assets.slice(1)}];
  let active=0,max=0,bridged=0;
  h.scope.fetch=async(url,opts)=>{
    if(String(url).startsWith('https://assets.tantantan.tech/'))return new Response('',{status:503});
    assert(String(url).startsWith('https://scoretracker-paper-preview-bridge.'));bridged++;active++;max=Math.max(max,active);
    await new Promise(resolve=>setTimeout(resolve,3));active--;return new Response(img,{headers:{'content-type':'image/jpeg'}});
  };
  const pages=await h.scope.storedPages(db,uid,rid,[1]);
  assert.equal(bridged,11);assert(max<=3,'reads must not exceed the ECS connection limit');
  assert.equal(pages[0].url,'data:image/jpeg;base64,'+img.toString('base64'));assert.equal(pages[0].regions.length,10);
  const fallbackPath=`${uid}/${rid}/2-${crypto.randomUUID()}`;h.blobs.set(fallbackPath,img);
  h.tables.score_tracker_paper_materials[0].pages.push({page:2,role:'work',path:fallbackPath,mime:'image/jpeg',bytes:img.length,detail_images:[]});
  r=await h.call({action:'sources',request_id:rid});assert.equal(r.status,200);const sources=(await r.json()).pages;
  assert(sources[0].url.startsWith('https://assets.tantantan.tech/'));assert(sources[0].fallback_url.startsWith('https://scan.test/'));assert(sources[1].url.startsWith('https://scan.test/'));
  h.scope.fetch=async()=>new Response('',{status:503});h.blobs.set(assets[0].path,img);
  const fallback=await h.scope.storedPages(db,uid,rid,[1]).catch(()=>null);
  assert.equal(fallback,null,'missing details must never silently become successful results');
  for(const asset of assets)h.blobs.set(asset.path,img);
  assert.equal((await h.scope.storedPages(db,uid,rid,[1]))[0].url,'data:image/jpeg;base64,'+img.toString('base64'));
  const {JSDOM}=require('jsdom'),fs=require('node:fs');
  const dom=new JSDOM('<main><a><img></a></main>',{url:'https://preview.example/',runScripts:'outside-only'}),window=dom.window;
  window.eval(fs.readFileSync('paper-review-support.js','utf8'));
  const source={url:'https://assets.example/image',fallback_url:'https://backup.example/image'};let tried=[];
  window.fetch=async url=>{tried.push(url);if(url===source.fallback_url)return new Response('image');throw Error('offline');};
  assert.equal(await (await window.ScorePaperSupport.fetchScan(source)).text(),'image');assert.deepEqual(tried,['https://assets.example/image','https://backup.example/image']);
  source.url='https://assets.example/image';const main=window.document.querySelector('main'),image=main.querySelector('img'),link=main.querySelector('a');
  image.src=link.href=source.url;const dispose=window.ScorePaperSupport.useFallbackImages(main,[source]);image.dispatchEvent(new window.Event('error'));
  assert.equal(image.src,source.fallback_url);assert.equal(link.href,source.fallback_url);dispose();dom.window.close();
  console.log('PASS: signed fixed-host bridge, ECS-to-backup fallback, mixed pages and bounded concurrent image reads');
})().catch(e=>{console.error(e);process.exitCode=1});
